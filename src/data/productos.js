// Generador configurable de pasos de graduación
export const generarGraduaciones = (paso = 0.25, min = -0.50, max = -8.00) => {
  const lista = [];
  for (let val = min; val >= max - 0.001; val -= paso) {
    lista.push(val.toFixed(2));
  }
  return lista;
};

