// Formateador de moneda MXN
export const formatMXN = (cantidad) => {
  return new Intl.NumberFormat('es-MX', {
    style: 'currency',
    currency: 'MXN',
    minimumFractionDigits: 2
  }).format(cantidad || 0);
};

// Calcula existencia total de un producto sumando todas sus graduaciones
export const calcularStockTotal = (producto) => {
  if (!producto || !producto.stockPorGraduacion) return 0;
  return Object.values(producto.stockPorGraduacion).reduce((acc, val) => acc + (val || 0), 0);
};

// Obtiene existencia de una graduación específica
export const obtenerStockGraduacion = (producto, graduacion) => {
  if (!producto || !producto.stockPorGraduacion) return 0;
  return producto.stockPorGraduacion[graduacion] || 0;
};
